// gtest for oriented 3D-IoU. Mirrors prototypes/python/tests/test_kitti_boxes.py so the C++ and
// Python geometry stay in lockstep. KITTI camera coords: BEV is (x, z), y is DOWN, so the box
// spans [y-h, y] vertically.
#include <gtest/gtest.h>

#include <cmath>

#include "kf_tracker/box3d.hpp"

using kf_tracker::Box3D;
using kf_tracker::iou3d;
using kf_tracker::iouBev;

namespace {
Box3D makeBox(double x, double z, double yaw = 0.0) {
  Box3D b;
  b.x = x;
  b.y = 1.5;
  b.z = z;
  b.yaw = yaw;
  b.l = 4.0;
  b.w = 2.0;
  b.h = 1.5;
  return b;
}
}  // namespace

TEST(Box3D, SelfIouIsOne) {
  const Box3D a = makeBox(0.0, 0.0);
  EXPECT_NEAR(iou3d(a, a), 1.0, 1e-9);
  EXPECT_NEAR(iouBev(a, a), 1.0, 1e-9);
}

TEST(Box3D, DisjointBoxesGiveZero) {
  const Box3D a = makeBox(0.0, 0.0);
  const Box3D b = makeBox(100.0, 100.0);
  EXPECT_NEAR(iou3d(a, b), 0.0, 1e-12);
}

TEST(Box3D, AxisAlignedHalfOverlapMatchesClosedForm) {
  // Shift along the length axis by l/2 = 2.0 -> BEV overlap is 2.0 x 2.0 = 4.0 of 8.0 each.
  const Box3D a = makeBox(0.0, 0.0);
  const Box3D b = makeBox(2.0, 0.0);
  const double inter_area = 2.0 * 2.0;
  const double expected_bev = inter_area / (8.0 + 8.0 - inter_area);
  EXPECT_NEAR(iouBev(a, b), expected_bev, 1e-9);

  // Same height range, so the 3D IoU uses the same area ratio scaled by full height overlap.
  const double inter_vol = inter_area * 1.5;
  const double expected_3d = inter_vol / (8.0 * 1.5 + 8.0 * 1.5 - inter_vol);
  EXPECT_NEAR(iou3d(a, b), expected_3d, 1e-9);
}

TEST(Box3D, NoHeightOverlapGivesZeroEvenWhenBevOverlaps) {
  Box3D a = makeBox(0.0, 0.0);
  Box3D b = makeBox(0.0, 0.0);
  b.y = a.y - a.h - 0.5;  // b sits entirely above a (y is down)
  EXPECT_NEAR(iouBev(a, b), 1.0, 1e-12);
  EXPECT_NEAR(iou3d(a, b), 0.0, 1e-12);
}

TEST(Box3D, RotatedBoxOverlapIsSymmetricAndBounded) {
  const Box3D a = makeBox(0.0, 0.0, 0.0);
  const Box3D b = makeBox(0.5, 0.3, M_PI / 4.0);
  const double ab = iou3d(a, b);
  const double ba = iou3d(b, a);
  EXPECT_NEAR(ab, ba, 1e-9);
  EXPECT_GT(ab, 0.0);
  EXPECT_LT(ab, 1.0);
}

TEST(Box3D, NinetyDegreeRotationAboutSameCenterMatchesClosedForm) {
  // 4x2 box rotated 90 degrees about its own center -> intersection is the 2x2 square.
  const Box3D a = makeBox(0.0, 0.0, 0.0);
  const Box3D b = makeBox(0.0, 0.0, M_PI / 2.0);
  const double inter_area = 2.0 * 2.0;
  const double expected = inter_area / (8.0 + 8.0 - inter_area);
  EXPECT_NEAR(iouBev(a, b), expected, 1e-9);
}

